export interface Cp1250Result {
  bytes: Uint8Array;
  /** liczba znaków spoza CP1250, zastąpionych znakiem "?" */
  lost: number;
}

export function encodeCp1250(str: string): Cp1250Result {
  const bytes = new Uint8Array(str.length);
  let lost = 0;
  for (let i = 0; i < str.length; i++) {
    const ch = str[i];
    const code = str.charCodeAt(i);
    if (code < 0x80) {
      bytes[i] = code;
    } else if (CP1250[ch] != null) {
      bytes[i] = CP1250[ch];
    } else {
      bytes[i] = 0x3f; // "?"
      lost++;
    }
  }
  return { bytes, lost };
}
